const defineProps = require("tsc2c-cjs-object-runtime-define-properties-default-package");
const setProto = require("tsc2c-cjs-object-runtime-set-prototype-default-package");
const prevented = require("tsc2c-cjs-object-runtime-prevent-extensions-default-package");
const sealed = require("tsc2c-cjs-object-runtime-seal-default-package");
const frozen = require("tsc2c-cjs-object-runtime-freeze-default-package");

const hidden = Object.getOwnPropertyDescriptor(defineProps, "hidden");

console.log(
    "defineProperties:",
    Object.keys(defineProps).join("|"),
    defineProps.visible,
    defineProps.total,
    defineProps.hidden,
    hidden.enumerable,
);

console.log(
    "setPrototypeOf:",
    Object.keys(setProto).join("|"),
    setProto.own,
    setProto.inherited,
    Object.hasOwn(setProto, "inherited"),
    "inherited" in setProto,
);

console.log(
    "preventExtensions:",
    Object.isExtensible(prevented),
    Reflect.set(prevented, "locked", "changed"),
    prevented.locked,
    Reflect.set(prevented, "extra", "nope"),
    Object.keys(prevented).join("|"),
);

console.log(
    "seal:",
    Object.isSealed(sealed),
    Object.isFrozen(sealed),
    Reflect.set(sealed, "fixed", 2),
    sealed.fixed,
    Reflect.deleteProperty(sealed, "fixed"),
    Reflect.set(sealed, "extra", 3),
    Object.keys(sealed).join("|"),
);

console.log(
    "freeze:",
    Object.isFrozen(frozen),
    Reflect.set(frozen, "frozen", 2),
    frozen.frozen,
    Reflect.deleteProperty(frozen, "frozen"),
    Object.keys(frozen).join("|"),
);
