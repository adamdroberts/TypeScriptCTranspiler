// Module goal (inherits "type": "module"): require() destructuring reads the
// runtime-owned CommonJS exports, including references hoisted above it.
let seen = "";

function fallback(label: string): string {
    seen += label;
    return "fallback-" + label;
}

const {
    label = fallback("label"),
    missing = fallback("missing"),
    "item-count": itemCount,
    add: renamedAdd,
    enabled,
    absent: renamedMissing = fallback("renamed"),
    ...rest
} = require("tsc2c-cjs-destructure-package");

function total(): number {
    return renamedAdd(30, 12);
}

console.log(label, itemCount, enabled, total());
console.log(missing, renamedMissing, seen);
console.log("rest:", rest.extra, Object.keys(rest).sort().join(","));

// Destructured module bindings must stay rooted across collections.
let churn = 0;
for (let i = 0; i < 200000; i++) churn += ("garbage-" + i).length;
console.log(churn > 0, missing, renamedMissing, rest.extra);
