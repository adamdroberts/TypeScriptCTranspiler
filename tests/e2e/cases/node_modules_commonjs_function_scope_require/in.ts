function addBound(left: number, right: number): number {
    const pkg = require("tsc2c-cjs-function-scope-named");
    return pkg.add(left, right);
}

function addDestructured(left: number, right: number): number {
    const { add } = require("tsc2c-cjs-function-scope-named");
    return add(left, right);
}

function multiplyBound(left: number, right: number): number {
    const multiply = require("tsc2c-cjs-function-scope-default");
    return multiply(left, right);
}

function multiplyDirect(left: number, right: number): number {
    return require("tsc2c-cjs-function-scope-default")(left + 1, right);
}

console.log(addBound(2, 3), addDestructured(4, 5), multiplyBound(6, 7), multiplyDirect(7, 8));
