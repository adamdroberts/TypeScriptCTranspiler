import * as cryptoNs from "crypto";
import * as nodeCryptoNs from "node:crypto";
import cryptoDefault,{getHashes,getHashes as alias} from "crypto";
import nodeCryptoDefault from "node:crypto";
const hashes=getHashes();
console.log("types:",Array.isArray(hashes)&&hashes.every(name=>typeof name==="string"));
console.log("unique:",hashes.every((name,index)=>hashes.indexOf(name)===index));
console.log("lookup:",hashes.includes("sha3-256")&&hashes.includes("blake2s256"));
console.log("aliases:",[cryptoNs.getHashes().join("|"),nodeCryptoNs.getHashes().join("|"),cryptoDefault.getHashes().join("|"),nodeCryptoDefault.getHashes().join("|"),alias().join("|")].every(value=>value===hashes.join("|")));
console.log("extra:",getHashes("ignored",123).join("|")===hashes.join("|"));
